"""Generates the table-driven Rust test files in src/tests/ (one #[test] per case).

    python tests/gen/rust_cases.py

Each case is a plain #[test] so `cargo test` names exactly what failed. The
expected values are worked out here independently of the Rust code (CLDR
plural rules, digit grouping, Luhn mod 32, the catalogs read from
src/locales), or are properties every input must keep (never panic,
idempotent, round trips). Re-run after changing the cases; the output is
committed like any other source.
"""
