LANG_CODES = ["en", "es", "ru", "pl", "ja"]


def cldr(lang, n):
    n10, n100 = n % 10, n % 100
    if lang in ("en", "es"):
        return "one" if n == 1 else "other"
    if lang == "ja":
        return "other"
    if lang == "ru" and n10 == 1 and n100 != 11:
        return "one"
    if lang == "pl" and n == 1:
        return "one"
    if 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        return "few"
    return "many"


def group(lang, n):
    digits = str(abs(n))
    if len(digits) < (5 if lang == "es" else 4):
        return str(n)
    sep = {"en": ",", "ja": ",", "es": ".", "ru": "\u00a0", "pl": "\u00a0"}[lang]
    out = ""
    for i, c in enumerate(digits):
        if i > 0 and (len(digits) - i) % 3 == 0:
            out += sep
        out += c
    return ("-" if n < 0 else "") + out


def substitute(template, args):
    """What i18n::substitute does, with every argument as text or number."""
    out, rest = "", template
    while "{" in rest:
        start = rest.index("{")
        out += rest[:start]
        after = rest[start + 1:]
        end = after.find("}")
        if end >= 0 and all(c.isascii() and (c.isalnum() or c == "_") for c in after[:end]):
            name = after[:end]
            out += args[name] if name in args else rest[start:start + end + 2]
            rest = after[end + 1:]
        else:
            out += "{"
            rest = after
    return out + rest


def placeholders(text):
    return sorted(set(re.findall(r"\{([A-Za-z0-9_]+)\}", text)))


