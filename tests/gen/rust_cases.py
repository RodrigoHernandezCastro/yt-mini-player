HEADER = "// Generated by tests/gen/rust_cases.py: edit the generator, not this file.\n"


def rs(text):
    """A Rust string literal."""
    out = ['"']
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif code < 0x20 or code == 0x7F or 0x80 <= code < 0xA0 or 0x202A <= code <= 0x202E or 0x2066 <= code <= 0x2069:
            out.append("\\u{%x}" % code)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def ident(text):
    name = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return (name or "case")[:60].rstrip("_")


def bool_assert(line):
    """`assert_eq!(x, true)` → `assert!(x)` (clippy's bool_assert_comparison)."""
    m = re.fullmatch(r"(\s*)assert_eq!\((.*), (true|false)\);", line)
    if not m:
        return line
    indent, expr, value = m.groups()
    return f"{indent}assert!({expr});" if value == "true" else f"{indent}assert!(!({expr}));"


class File:
    """One generated file: a list of #[test] functions with unique names."""

    def __init__(self, name, uses):
        self.name = name
        self.uses = uses
        self.parts = []
        self.names = set()
        self.count = 0

    def raw(self, code):
        self.parts.append(code)

    def test(self, label, body, attrs=""):
        base = ident(label)
        # A single word, or the name of a function the test calls, would
        # shadow that function (`substitute`, `clean_name`).
        if "_" not in base or re.search(r"\b" + base + r"\(", body):
            base += "_case"
        name = base
        n = 2
        while name in self.names or re.search(r"\b" + name + r"\(", body):
            name = f"{base}_{n}"
            n += 1
        self.names.add(name)
        self.count += 1
        body = "\n".join(bool_assert(line) for line in body.split("\n"))
        indented = "\n".join(("    " + line) if line else "" for line in body.strip("\n").split("\n"))
        self.parts.append(f"#[test]\n{attrs}fn {name}() {{\n{indented}\n}}\n")

    def write(self):
        text = HEADER + "\n" + self.uses.strip() + "\n\n" + "\n".join(self.parts)
        (OUT / self.name).write_text(text, encoding="utf-8")
        return self.count


